/*
问题概述
给定正整数 n（3≤n≤10000），将其拆分为若干个互不相同的自然数之和，使得这些数的乘积最大。输出拆分方案（升序）和最大乘积。

算法思路
贪心拆分：为了使乘积最大，应尽可能多地拆分，且从较小的数开始（但避免使用1，因为1会浪费和）。通常从2开始连续取自然数，直到和大于等于 n。
调整和：若拆分和超过 n，需通过去掉或调整数使和恰好为 n。
高精度计算：由于乘积可能很大，需用高精度乘法计算。
 */

#include<iostream>
using namespace std;
int a[10001]={};//存储拆分出的自然数
int s[10001]={};//高精度数组，s[1]是个位，len是当前位数。
int n,len=1;//n：输入的正整数。len：高精度数字的位数，初始为1。
//高精度×   逐位相乘并处理进位。
//s数组存储高精度数字，s[1]是个位，s[2]是十位，依此类推
//len是当前数字的位数

//mul()函数不需要接收 s和 len作为参数
//
//它直接操作全局的 s数组和 len
//
//这种修改对所有函数都可见
void mul(int x)
{
    for(int i=1;i<=len;i++)//这行代码将当前高精度数字的每一位都乘以 x。注意：此时可能会有某一位大于等于10，但还没有处理进位
        s[i]*=x;
    //处理进位（低位到高位）
    for(int i=1;i<=len;i++)//遍历当前所有位（i=1到 i=len）
    {
        s[i+1]+=s[i]/10;
        s[i]%=10;
    }
    //处理最高位可能产生的新进位：s[len+1]可能不为0（有进位）.为什么用while因为可能进位多位。
    while(s[len+1]>0)
    {
        //如果有进位，就需要增加位数（len++）
        len++;
        //然后继续处理新一位的进位
        s[len+1]+=s[len]/10;
        s[len]%=10;
    }
}

int main()
{
    cin>>n;
    if(n==3)//当 n=3时，最优是不拆分（乘积为3），拆分 1+2的乘积为2。
    {
        cout<<3<<endl;
        cout<<3<<endl;
        return 0;
    }
    if(n==4)//当 n=4时，最优是不拆分（乘积为4），拆分 1+3的乘积为3。
    {
        cout<<4<<endl;
        cout<<4<<endl;
        return 0;
    }
    s[0]=s[1]=1;
    int Sum=0,tot=0;//Sum：当前拆分数的和。tot：拆分数的个数。
    //从2开始依次将自然数加入数组，并累加和，直到和不少于 n。例如 n=10时：
    for(int i=2;Sum<n;Sum+=i,i++)
        a[++tot]=i;
    if(Sum>n+1)//Sum > n+1：和比 n至少多2。处理：去掉第 (Sum-n-1)个数（即数值为 Sum-n的数）。
        a[Sum-n-1]=0;//数组a中，a[k]存储的数值是k+1。所以数值x在数组中的下标是x-1
    else if(Sum==n+1)//Sum == n+1：和比 n多1。处理：去掉最小的数2，并将最大的数加1。
        a[tot]++,a[1]=0;
    for(int i=1;i<=tot;i++)//历所有拆分出的数
    {
        if(a[i])//如果a[i]不为0，输出这个数
        {
            cout<<a[i]<<' ';
            mul(a[i]);//并调用mul(a[i])计算乘积
        }
    }
    cout<<endl;
    //高精度数组s是倒序存储的（s[1]是个位）
    for(int i=len;i>=1;i--)
        cout<<s[i];
    cout<<endl;
    return 0;
}
